export function drawScenes(random = Math.random) {
  return questionBank.map(({ variants, ...slot }) => {
    const index = Math.min(variants.length - 1, Math.max(0, Math.floor(random() * variants.length)));
    return { ...slot, slot: slot.id, ...variants[index] };
  });
}
